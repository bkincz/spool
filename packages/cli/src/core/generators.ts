/**
 * The workspace-root `spool.vite.ts`. Apps' vite configs call `spoolApp(name)`
 * from it, which reads spool.json at config load time. Dependency-free
 * (node:fs and node:path only) so it runs in any app.
 */
function spoolViteHelper(): string {
	return `/**
 * Generated by spool. Reads spool.json when Vite loads the config and derives
 * the app's dev server and Module Federation settings. Edit spool.json, not
 * this file.
 */
import { existsSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

export interface SpoolAppEntry {
  type: "host" | "remote";
  path: string;
  port: number;
  url?: string;
  urls?: Record<string, string>;
  remotes?: string[];
  exposes?: Record<string, string>;
}

export interface SpoolServerConfig {
  proxy?: Record<string, unknown>;
  headers?: Record<string, string>;
  host?: boolean | string;
  cors?: boolean;
}

export interface SpoolManifest {
  name: string;
  shared?: string[];
  server?: SpoolServerConfig;
  apps: Record<string, SpoolAppEntry>;
}

export interface SpoolAppConfig {
  /** Vite server/preview settings for this app. */
  server: SpoolServerConfig & { port: number; strictPort: boolean };
  /** Options for the federation() plugin from @module-federation/vite. */
  federation: {
    name: string;
    filename?: string;
    manifest?: boolean;
    remotes?: Record<string, string>;
    exposes?: Record<string, string>;
    shared: Record<string, { singleton: boolean }>;
    dts: false;
  };
}

function findManifest(from: string): string {
  let dir = resolve(from);
  for (;;) {
    const candidate = join(dir, "spool.json");
    if (existsSync(candidate)) return candidate;
    const parent = dirname(dir);
    if (parent === dir) throw new Error("spool.vite: no spool.json found above " + from);
    dir = parent;
  }
}

/**
 * Remote lookup order: SPOOL_REMOTE_<NAME> env var, the remote's url for the
 * SPOOL_ENV environment, its default "url" (production builds only, so dev
 * keeps hitting local servers), then the local dev server.
 */
function remoteUrl(name: string, app: SpoolAppEntry, command: SpoolCommand): string {
  const envKey = "SPOOL_REMOTE_" + name.toUpperCase().replace(/-/g, "_");
  const environment = process.env.SPOOL_ENV;
  const deployed =
    command === "build"
      ? (environment !== undefined ? app.urls?.[environment] : undefined) ?? app.url
      : undefined;
  return process.env[envKey] ?? deployed ?? "http://localhost:" + app.port + "/mf-manifest.json";
}

export type SpoolCommand = "build" | "serve";

/**
 * Shared deps the app does not declare in its own package.json are dropped,
 * so apps on different frameworks never share deps they don't install.
 */
function declaredShared(dir: string, deps: string[]): string[] {
  if (!deps.length) return deps;
  let declared: Set<string>;
  try {
    const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8")) as {
      dependencies?: Record<string, string>;
      devDependencies?: Record<string, string>;
    };
    declared = new Set([
      ...Object.keys(pkg.dependencies ?? {}),
      ...Object.keys(pkg.devDependencies ?? {}),
    ]);
  } catch {
    // Sharing nothing is safe (the app just bundles its own copies); sharing
    // deps the app may not have installed is not.
    console.warn(
      "[spool] could not read " + join(dir, "package.json") + "; sharing no deps for this app. Run spool doctor."
    );
    return [];
  }
  // "@scope/pkg/subpath" is declared through its package, "@scope/pkg".
  const packageName = (dep: string): string => {
    const parts = dep.split("/");
    return dep.startsWith("@") ? parts.slice(0, 2).join("/") : parts[0]!;
  };
  return deps.filter(dep => declared.has(packageName(dep)));
}

const ENV_REF = /\\$\\{([A-Za-z_][A-Za-z0-9_]*)(?::-([^}]*))?\\}/g;

/**
 * Expands \${VAR} and \${VAR:-fallback} through the manifest server block, so a
 * proxy target can differ per machine without anyone editing a vite config.
 */
function expandEnv<T>(value: T): T {
  if (typeof value === "string") {
    return value.replace(ENV_REF, (_, name: string, fallback?: string) =>
      process.env[name] ?? fallback ?? ""
    ) as T;
  }
  if (Array.isArray(value)) return value.map(expandEnv) as T;
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, inner]) => [key, expandEnv(inner)])
    ) as T;
  }
  return value;
}

export function spoolApp(
  name: string,
  from: string = process.cwd(),
  command: SpoolCommand = "serve"
): SpoolAppConfig {
  const manifest = JSON.parse(readFileSync(findManifest(from), "utf8")) as SpoolManifest;
  const app = manifest.apps[name];
  if (!app) throw new Error('spool.vite: no app named "' + name + '" in spool.json');

  // Singleton for every share: duplicated react breaks hooks, and workspace
  // packages often carry module-level state that must resolve to one copy.
  // Non-singleton workspace shares also hit a @module-federation/vite dev bug
  // where the generated loadShare module references __mfLocalShare without
  // importing it, crashing the app at boot.
  const shared = Object.fromEntries(
    declaredShared(from, manifest.shared ?? []).map(dep => [dep, { singleton: true }])
  );
  // cors covers dev and vite preview, where hosts fetch remotes cross-origin.
  // Manifest settings come last so a workspace can override the defaults,
  // but never the port, which the app entry owns.
  const server = {
    port: app.port,
    strictPort: true,
    cors: true,
    ...expandEnv(manifest.server ?? {}),
  };

  if (app.type === "host") {
    const remotes: Record<string, string> = {};
    for (const remote of app.remotes ?? []) {
      const target = manifest.apps[remote];
      if (!target) {
        throw new Error('spool.vite: host "' + name + '" references unknown remote "' + remote + '"');
      }
      remotes[remote] = remoteUrl(remote, target, command);
    }
    // dts:false: spool types remotes via src/remotes.d.ts, so the federation
    // DTS archive is redundant and its dev-server download is flaky.
    return { server, federation: { name, remotes, shared, dts: false } };
  }

  return {
    server,
    federation: {
      name,
      filename: "remoteEntry.js",
      // Dev serves mf-manifest.json automatically; builds only emit it with
      // this flag, and hosts load remotes by their manifest URL.
      manifest: true,
      exposes: app.exposes ?? {},
      shared,
      dts: false,
    },
  };
}
`
}

/*
 *   CI WORKFLOWS
 ***************************************************************************************************/
export function ciWorkflows(m: Manifest): FileMap {
	const files: FileMap = {}
	for (const [name, app] of Object.entries(m.apps)) {
		if (!app.deploy) continue
		files[`.github/workflows/deploy-${name}.yml`] = ciWorkflow(m, name, app)
	}
	return files
}

const LOCKFILES = {
	pnpm: 'pnpm-lock.yaml',
	npm: 'package-lock.json',
	yarn: 'yarn.lock',
} as const

const INSTALL_COMMANDS = {
	pnpm: 'pnpm install --frozen-lockfile',
	npm: 'npm ci',
	yarn: 'yarn install --frozen-lockfile',
} as const

function ciWorkflow(m: Manifest, appName: string, app: AppConfig): string {
	const pm = m.packageManager
	const pnpmSetup =
		pm === 'pnpm'
			? `
            - uses: pnpm/action-setup@v6
`
			: ''

	return `# Generated by spool ci. The deploy command is copied from spool.json;
# rerun \`spool ci --force\` after changing it there.
name: Deploy ${appName}

on:
    workflow_dispatch:
    push:
        branches: [main]
        paths:
            - 'apps/${appName}/**'
            - 'spool.json'
            - '${HELPER_FILE}'
            - 'package.json'
            - '${LOCKFILES[pm]}'

jobs:
    deploy:
        runs-on: ubuntu-latest
        steps:
            - uses: actions/checkout@v7
${pnpmSetup}
            - uses: actions/setup-node@v6
              with:
                  node-version: 24
                  cache: '${pm}'

            - name: Install
              run: ${INSTALL_COMMANDS[pm]}

            - name: Build
              working-directory: ${app.path}
              run: ${pm} run build

            # Add the secrets your deploy command needs, e.g.
            # env:
            #     CLOUDFLARE_API_TOKEN: \${{ secrets.CLOUDFLARE_API_TOKEN }}
            - name: Deploy
              working-directory: ${app.path}
              run: ${app.deploy}
`
}

