const json = (value: unknown): string => `${JSON.stringify(value, null, 2)}\n`

/** Relative import path from an app folder up to the workspace-root helper. */
const helperImport = (appPath: string): string => {
	const depth = appPath.split('/').filter(Boolean).length
	return `${'../'.repeat(depth)}${HELPER_FILE.replace(/\.ts$/, '')}`
}

/** The generated helpers as a writable FileMap; `spool add` uses it to self-heal. */
export function helperFile(): FileMap {
	return {
		[HELPER_FILE]: spoolViteHelper(),
		[WORKSPACE_FILE]: spoolWorkspaceHelper(),
	}
}

/**
 * Reads spool.json at import time like the vite helper does, so anything
 * built on it stays right as apps come and go. A hand-kept copy of the app
 * list is the thing this exists to delete.
 */
function spoolWorkspaceHelper(): string {
	return `/*
 * Generated by spool. Reads spool.json when it is imported, so the app list
 * is never stale. Edit spool.json, not this file.
 */
import { existsSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

export type SpoolFramework = "react" | "svelte" | "vue";

export interface WorkspaceApp {
  name: string;
  type: "host" | "remote";
  framework: SpoolFramework;
  port: number;
  /** Absolute path to the app folder. */
  dir: string;
  /** Absolute path to the app\u2019s src folder. */
  src: string;
  /** Remotes a host consumes; empty for a remote. */
  remotes: string[];
  /** Modules a remote exposes; empty for a host. */
  exposes: Record<string, string>;
}

interface RawApp {
  type: "host" | "remote";
  framework?: SpoolFramework;
  path: string;
  port: number;
  remotes?: string[];
  exposes?: Record<string, string>;
}

function findManifest(from: string): string {
  let dir = resolve(from);
  for (;;) {
    const candidate = join(dir, "spool.json");
    if (existsSync(candidate)) return candidate;
    const parent = dirname(dir);
    if (parent === dir) throw new Error("spool.workspace: no spool.json found above " + from);
    dir = parent;
  }
}

const manifestPath = findManifest(import.meta.dirname);
const manifest = JSON.parse(readFileSync(manifestPath, "utf8")) as {
  name: string;
  shared?: string[];
  addons?: string[];
  apps: Record<string, RawApp>;
};

/** Absolute path to the workspace root, where spool.json lives. */
export const root: string = dirname(manifestPath);

export const workspaceName: string = manifest.name;
export const shared: string[] = manifest.shared ?? [];
export const addons: string[] = manifest.addons ?? [];

export const apps: WorkspaceApp[] = Object.entries(manifest.apps).map(([name, entry]) => ({
  name,
  type: entry.type,
  framework: entry.framework ?? "react",
  port: entry.port,
  dir: join(root, entry.path),
  src: join(root, entry.path, "src"),
  remotes: entry.remotes ?? [],
  exposes: entry.exposes ?? {},
}));

export const hosts: WorkspaceApp[] = apps.filter(entry => entry.type === "host");
export const remotes: WorkspaceApp[] = apps.filter(entry => entry.type === "remote");

/** Every app\u2019s src folder, for sweeps that should cover the whole workspace. */
export const srcDirs: string[] = apps.map(entry => entry.src);

export function app(name: string): WorkspaceApp {
  const found = apps.find(entry => entry.name === name);
  if (!found) throw new Error(\`spool.workspace: no app named "\${name}" in spool.json\`);
  return found;
}
`
}

