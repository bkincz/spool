function appPackageJson(
	m: Manifest,
	appName: string,
	app: AppConfig,
	extras: TemplateExtras
): string {
	const { dependencies, devDependencies } = appDependencies(m, app)

	// The example button lives in the ladle ui workspace package; npm and yarn
	// link workspace packages by bare name, pnpm needs the workspace protocol.
	if (extras.uiButton && app.framework === 'react' && app.type === 'remote') {
		dependencies.ui = m.packageManager === 'pnpm' ? 'workspace:*' : '*'
	}

	return json({
		name: appName,
		version: '0.0.0',
		private: true,
		type: 'module',
		engines: { node: NODE_RANGE },
		scripts: {
			dev: 'vite',
			build: 'vite build',
			preview: 'vite preview',
			'type-check': 'tsc --noEmit',
			...(m.addons.includes('test') ? TEST_SCRIPTS : {}),
		},
		dependencies: sortKeys(dependencies),
		devDependencies: sortKeys(devDependencies),
	})
}

function sortKeys(record: Record<string, string>): Record<string, string> {
	return Object.fromEntries(Object.entries(record).sort(([a], [b]) => a.localeCompare(b)))
}

function appTsConfig(framework: Framework): string {
	// Compiler options like the JSX runtime are per app, so one framework's
	// settings never leak into another's through the shared base config. `@`
	// maps to src (matched by the vite alias) so apps import from "@/...".
	return json({
		extends: '../../tsconfig.base.json',
		compilerOptions: {
			...TEMPLATES[framework].compilerOptions,
			baseUrl: '.',
			paths: { '@/*': ['./src/*'] },
		},
		include: ['src', 'vite.config.ts'],
	})
}

function viteConfig(appName: string, app: AppConfig, sentry: boolean): string {
	const plugin = TEMPLATES[app.framework].vitePlugin
	const sentryPlugin = sentry ? sentryVitePlugin() : undefined

	const imports = [
		'import { defineConfig } from "vite";',
		'import { resolve as resolvePath } from "node:path";',
		plugin.importLine,
		'import { federation } from "@module-federation/vite";',
		...(sentryPlugin ? [sentryPlugin.importLine] : []),
		`import { spoolApp } from "${helperImport(app.path)}";`,
	].join('\n')

	const plugins = [
		`${plugin.call}`,
		'federation(app.federation)',
		...(sentryPlugin ? [sentryPlugin.entry] : []),
	]

	return `${imports}

// Generated by spool. Wiring comes from spool.json via spool.vite.ts at
// startup. Edit spool.json, not this file. The command tells the helper
// whether deployed remote urls apply (build) or local dev servers do (serve).
export default defineConfig(({ command }) => {
  const app = spoolApp(${JSON.stringify(appName)}, import.meta.dirname, command);
  return {
    server: app.server,
    preview: app.server,
    resolve: { alias: { "@": resolvePath(import.meta.dirname, "src") } },
    plugins: [${plugins.join(', ')}],
    // Module Federation needs top-level await; lock the build target.
    build: { target: "esnext", minify: false${sentry ? ', sourcemap: true' : ''} },
  };
});
`
}

function indexHtml(appName: string, framework: Framework): string {
	const entry = TEMPLATES[framework].htmlEntry
	return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${appName}</title>
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="${entry}"></script>
  </body>
</html>
`
}

function remoteTypings(refs: RemoteRef[]): string {
	return refs.map(ref => TEMPLATES[ref.framework].remoteTyping(ref.name)).join('')
}
